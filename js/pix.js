function pixSprite(k) {
  const a = HERO_PIX[k], N = 20, c = document.createElement('canvas'); c.width = c.height = N; const g = c.getContext('2d');
  const col = ch => ch === '.' || !ch ? null : (a.pal[ch] || PIX_PAL[ch] || null);
  const px = new Array(N * N).fill(null);
  a.g.forEach((row, y) => { for (let x = 0; x < 18; x++) { const cc = col(row[x]); if (cc) px[(y + 1) * N + x + 1] = cc; } });
  const out = px.slice();
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) if (!px[y * N + x]) for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
    const nx = x + dx, ny = y + dy; if (nx >= 0 && ny >= 0 && nx < N && ny < N && px[ny * N + nx]) { out[y * N + x] = PIX_PAL.k; break; }
  }
  for (let i = 0; i < N * N; i++) if (out[i]) { g.fillStyle = out[i]; g.fillRect(i % N, Math.floor(i / N), 1, 1); }
  return c;
}
const _spriteGetPix = Sprites.get.bind(Sprites);
